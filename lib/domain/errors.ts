/**
 * Builds the i18n key the frontend uses to translate an error code.
 *
 * @param code - Stable error code.
 * @returns Key inside the `errors` message namespace.
 */
export function errorMessageKey(code: ErrorCode): string {
  return `errors.${code}`;
}
